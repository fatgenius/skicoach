//   第 3 关：kneeFlexion() —— 用“小腿角 - 大腿角 - 站直零偏”算出膝盖到底弯了多少度
//   第 4 关：WaistWindow   —— 收集腰部最近 1 秒的数据，像体操裁判一样去掉最高最低刺点，算晃动幅度
//   第 5 关：Hold          —— 拿着秒表的铁面裁判，越界动作连续保持够久（0.8秒或0.5秒）才吹哨报警
