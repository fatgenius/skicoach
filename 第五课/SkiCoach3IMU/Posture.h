// 第六部分：【第 4 关】腰部(W) 1 秒晃动放大镜与“体操裁判打分法”（percentile 与 WaistWindow）
// ============================================================================

// 函数：percentile —— 在一排已经【从小到大排好队】的数字里，找出排在某个百分比位置（比如前 10% 或前 90%）的数。
//
// 【参数说明】
//   • sorted   ：已经按从小到大排好序的角度数组（第 0 个最小，第 count-1 个最大）
//   • count    ：数组里一共有多少个数字
//   • fraction ：你要找百分之几的位置？（传 0.1f 就是找第 10% 的低位 P10；传 0.9f 就是找第 90% 的高位 P90）
//
// 【如果位置刚好落在两个数字中间怎么办？（线性插值）】
// 比如一共有 5 个数（下标 0, 1, 2, 3, 4），你要找 50%（0.5）的位置：(5-1) × 0.5 = 2.0，刚好是第 2 号下标。
// 但如果你找的位置算出来是下标 2.3（落在第 2 号和第 3 号之间，离 2 号距离 0.3）：
// 那就用：第2号的值 + 0.3 × (第3号的值 - 第2号的值)。就像在尺子两个刻度中间按比例估读一样精确！
inline float percentile(const float *sorted, size_t count, float fraction) {
    const float index = (count - 1) * fraction;      // 算出理想的小数下标位置
    const size_t lower = static_cast<size_t>(index); // 去掉小数点后面，得到左边相邻的整数下标
    if (lower + 1 == count) return sorted[lower];    // 如果刚好落在队尾最后一个数上，直接返回它
    // 落在 lower 和 lower+1 两个格子之间时，按小数距离 (index - lower) 做比例插值：
    return sorted[lower] + (index - lower) * (sorted[lower + 1] - sorted[lower]);
}

// 类：WaistWindow（腰部 1 秒滑动窗口）
//
// 【单板滑雪时，怎样用数学判断“腰部/骨盆是不是在乱晃”？】
// 滑行时，人的上身本来就需要保持一定的倾角（比如一直保持前倾 15° 不动，这是好姿势，不能报警！）。
// 真正糟糕的姿势是：在 1 秒钟之内，腰一会儿前倾、一会儿后仰，或者左右来回摇摆！
// 所以我们要看的是：【最近 1 秒钟之内，腰部角度来回变化的宽度（最大到最小的跨度）有多大】。
//
// 【为什么不用“最大值 - 最小值”，而要用“P90（前90%） - P10（前10%）”？】
// 想象体操比赛打分：为什么要“去掉一个最高分，去掉一个最低分”？
// 因为滑雪时雪板一旦压到一颗小冰粒，腰部传感器可能会有 1 帧数据因为剧烈震动突然跳到 140°（刺点噪声）。
// 如果用“最大值 - 最小值”，这 1 帧刺点就会骗过电脑，算出晃了 140° 而误报警！
// 而我们把 1 秒内的约 50 个数据从小到大排成一排，砍掉最头的 10% 和最尾的 10%，
// 用排在 90% 位置的数（P90）减去排在 10% 位置的数（P10），那 1~2 帧偶发的震动刺点就被完美扔掉了！
class WaistWindow {
public:
    // 函数：clear —— 清空整个滑动窗口（从 0 开始重新收集数据）。
    void clear() { head = count = 0; }

    // 函数：push —— 每收到一帧腰部传感器(W)的数据，就塞进这个 1 秒滑动窗口里，并尝试算出当前的晃动幅度 wave。
    //
    // 【参数说明】
    //   • now   ：这帧腰部数据到达的时刻（毫秒）
    //   • pitch ：当前腰部的前后俯仰角（度）
    //   • roll  ：当前腰部的左右侧倾角（度）
    //   • wave  ：输出参数（带 & 号）——如果窗口攒够了 1 秒，算出的晃动幅度 W 会填进这里带出去
    // 【返回值】
    //   • true  = 窗口已经攒满整整 1 秒、且有效数据够 35 个，成功算出了波动 W！
    //   • false = 刚启动还不到 1 秒，或者中途掉线/丢包太多，暂时不能算波动 W。
    bool push(uint32_t now, float pitch, float roll, float &wave) {
        // 第 1 步（查断流）：如果队列里已经有数据（count > 0），但现在的时间 now 比上一帧（at(count - 1).time）
        // 晚了超过 100 毫秒（GapMs），说明腰部传感器刚才断线过！以前的老数据不能要了，立刻 clear() 清空重来。
        if (count && now - at(count - 1).time > GapMs) clear();

        // 第 2 步（踢走 1 秒前的老数据）：
        // 只要队列里第 2 老的样本（at(1)）距离现在都已经达到或超过 1000 毫秒（WindowMs）了，
        // 就调用 pop() 把最老的第 1 个样本（at(0)）踢出队列。
        // （为什么要看 at(1) 而不是 at(0)？因为我们故意留 1 条刚好在 1 秒边界上或边界外一点点的老样本 at(0) 作证人，
        //   用来在下面第 5 步证明：“我们的窗口确实已经跨满整整 1000 毫秒了！”）
        while (count > 1 && now - at(1).time >= WindowMs) pop();

        // 第 3 步（防撑爆保护）：我们的环形队列总共准备了 128 个座位（Capacity = 128）。
        // 正常每秒 50 帧只占约 51 个座位；万一塞满了 128 个，就先把最老的踢掉一个腾出座位。
        if (count == Capacity) pop();

        // 第 4 步（新数据入座）：把当前这一帧的 {时间, 前后倾, 左右倾} 存进环形队列的队尾，总人数 count 加 1。
        samples[(head + count) % Capacity] = {now, pitch, roll};
        ++count;

        // 第 5 步（检查有没有攒满 1 秒）：
        // 看看队头最老的那条“证人样本” at(0)，距离现在满 1000 毫秒（WindowMs）了吗？
        // 如果还不到 1000 毫秒（比如刚按下 START 才过了 0.5 秒），时间不够长，先返回 false 不算波动。
        if (now - at(0).time < WindowMs) return false;

        // 第 6 步（挑出真正落在最近 1 秒内的样本）：
        // 如果队头那条“证人样本” at(0) 距离现在已经超过 1000 毫秒了（> WindowMs），那它只是用来证明时间跨度的，
        // 真正参与统计要从下标 1 开始（first = 1）；如果 at(0) 刚好等于 1000 毫秒，就从下标 0 开始（first = 0）。
        const size_t first = now - at(0).time > WindowMs ? 1 : 0;
        const size_t used = count - first; // used 就是最近 1.0 秒内真正有效的数据个数！

        // 第 7 步（检查数据够不够密）：
        // 传感器正常工作在 50Hz 时，1 秒钟应该收到 50 个左右的数据。
        // 如果 1 秒内收到的数据连 35 个都不到（used < 35），说明无线信号丢包太严重，或者传感器没设成 50Hz！
        // 用太稀疏的数据算波动不靠谱，直接返回 false 拒绝计算。
        if (used < 35) return false;

        // 第 8 步（复印到草稿纸并解决 ±180° 跨界难题）：
        // 把这 used 个有效样本从原队列复制到两张“排序草稿纸”（pitchWork 和 rollWork）上。
        // 复制的时候，顺便让每个历史角度减去当前最新一帧的角度（sample.pitch - pitch），再套上 wrap180！
        // 【这样做一举两得】：
        //   1) 所有数同时减去同一个常数，排好序后算“第90名 - 第10名”的差值完全不变！
        //   2) 如果腰部刚好在 +179° 和 -179° 分界线附近晃了 2°，直接排序会把 -179° 排第一、+179° 排最后，误算成晃了 358°！
        //      而减去最新读数再用 wrap180 展开后，它们都会变成 0° 附近的 ±2°，彻底消灭了跨界误报！
        for (size_t i = 0; i < used; ++i) {
            const auto &sample = at(first + i);
            pitchWork[i] = wrap180(sample.pitch - pitch);
            rollWork[i] = wrap180(sample.roll - roll);
        }

        // 第 9 步（在草稿纸上从小到大排队）：
        // 注意：绝对不能直接拿原队列 samples 去排序！因为原队列必须保持“按时间先后排队”，下一帧才知道谁最老该淘汰。
        // 所以我们只对两张草稿纸数组 pitchWork 和 rollWork 调用 std::sort 从小到大排序。
        std::sort(pitchWork, pitchWork + used);
        std::sort(rollWork, rollWork + used);

        // 第 10 步（体操裁判算分：P90 - P10）：
        // 分别算出前后倾（pitchSpan）和左右倾（rollSpan）的 P90 - P10 晃动宽度，
        // 然后用 std::max 挑出晃得更厉害的那个方向，作为最终的腰部波动幅度 wave（也就是串口打印的 W）！
        const float pitchSpan = percentile(pitchWork, used, 0.9f) -
                                percentile(pitchWork, used, 0.1f);
        const float rollSpan = percentile(rollWork, used, 0.9f) -
                               percentile(rollWork, used, 0.1f);
        wave = std::max(pitchSpan, rollSpan);
        return true; // 计算成功！
    }

private:
    // -------------------- 内部存储结构：巧妙的“环形数组（旋转寿司传送带）” --------------------
    // 为什么不用普通数组从 0 排到 count-1？
    // 因为如果用普通数组，每次踢掉队头第 0 个老数据时，后面 50 个数据都要全部往前搬一格座位，太浪费时间了！
    // 用“环形数组”就像一个有 128 个盘子的旋转寿司圆桌：
    //   • 我们只用 head 记住“当前最老的第 1 盘坐在几号位”，用 count 记住“桌上现在一共有几盘”。
    //   • 踢掉最老的一盘（pop）时，一盘都不用搬，只要把 head 往后指一格（(head + 1) % 128），总数 count 减 1 就行了！
    //   • 往队尾放新一盘时，直接放到 (head + count) % 128 的位置（走到 127 号末尾后，% 128 会自动绕回 0 号开头）！
    enum { Capacity = 128 };
    struct Sample { uint32_t time; float pitch; float roll; };
    Sample samples[Capacity] = {};  // 存放最近 1 秒腰部数据的环形圆桌队列
    float pitchWork[Capacity] = {}; // 专门用来给前后倾排序的“草稿纸数组”
    float rollWork[Capacity] = {};  // 专门用来给左右倾排序的“草稿纸数组”
    size_t head = 0;                // 队头指针：当前最老的那条数据在 samples 数组的几号下标
    size_t count = 0;               // 队列里当前一共存了多少条数据

    // 辅助小函数 at(index)：给你逻辑上的“第 index 老”的数据（0 是最老，count-1 是最新），自动算出它在圆桌上的真实下标。
    const Sample &at(size_t index) const { return samples[(head + index) % Capacity]; }

    // 辅助小函数 pop()：把队头最老的一条数据踢走（队头指针往后挪一步，总个数减 1）。
    void pop() {
        head = (head + 1) % Capacity;
        --count;
    }
};

